def _mdy(s):
    return [pd.Timestamp(f"{x[4:]}-{x[:2]}-{x[2:4]}") for x in s.split(",")]


def event_table():
    rows = [(d, "CPI") for d in _mdy(_CPI) + [pd.Timestamp(x) for x in _CPI_FUTURE]]
    rows += [(d, "NFP") for d in _mdy(_NFP) + [pd.Timestamp(x) for x in _NFP_FUTURE]]
    rows += [(pd.Timestamp(x), "FOMC") for x in _FOMC.split()]
    df = pd.DataFrame(rows, columns=["date", "event"])
    return df.groupby("date")["event"].apply(lambda s: "/".join(sorted(set(s)))).to_dict()


